import { render, screen, fireEvent, waitFor, cleanup } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
const mocks = vi.hoisted(() => ({ load: vi.fn(), grade: vi.fn(), fetch: vi.fn(), proxy: vi.fn() }));
vi.mock('../../api/collegeLearnerAssignmentService', () => ({ fetchCollegeAssignmentSubmissions: mocks.load, gradeCollegeAssignment: mocks.grade }));
vi.mock('@/shared/model/authStore', () => ({ useAuthStore: { getState: () => ({ user: { id: 'teacher' } }) } }));
vi.mock('@/shared/api', () => ({ getDocumentUrl: mocks.proxy }));
vi.mock('@/shared/api/ssoClient', () => ({ ssoClient: { fetch: mocks.fetch } }));
vi.mock('@/shared/config/logging', () => ({ getLogger: () => ({ warn: vi.fn() }) }));
vi.mock('react-hot-toast', () => ({ default: { error: vi.fn(), success: vi.fn() } }));
import { CollegeGradingModal } from '../CollegeGradingModal';
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.clearAllMocks(); });
it('opens the protected AI submission and saves an educator score including zero', async () => {
 const url = '/api/ai-tutor/assignment-submission?submissionId=submission';
 mocks.load.mockResolvedValue({ data: [{ learner_assignment_id: 'allocation', status: 'graded', grade_received: 80, submission_date: '2026-11-23T10:00:00Z', submission_files: [{ name: 'Answer.docx', url }], learner: { id: 'learner', name: 'Anusha', email: 'student@example.com' } }] });
 mocks.grade.mockResolvedValue({ data: { grade_received: 0, grade_percentage: 0 } });
 mocks.fetch.mockResolvedValue(new Response('document'));
 URL.createObjectURL = vi.fn(() => 'blob:document'); URL.revokeObjectURL = vi.fn();
 vi.spyOn(window, 'open').mockImplementation(() => null);
 const updated = vi.fn();
 render(<CollegeGradingModal isOpen onClose={vi.fn()} assignment={{ assignment_id: 'assignment', title: 'Worksheet', total_points: 100 }} onGradeUpdated={updated}/>);
 expect(await screen.findByText('Answer.docx')).toBeInTheDocument();
 expect(screen.queryByText('No files attached with this submission.')).not.toBeInTheDocument();
 fireEvent.click(screen.getByRole('button', { name: 'View File' }));
 await waitFor(() => expect(mocks.fetch).toHaveBeenCalledWith(url));
 expect(mocks.proxy).not.toHaveBeenCalled();
 fireEvent.change(screen.getByLabelText('Grade / Score (out of 100)'), { target: { value: '0' } });
 fireEvent.change(screen.getByLabelText('Educator Feedback'), { target: { value: 'Reviewed by educator' } });
 fireEvent.click(screen.getByRole('button', { name: 'Update Grade & Feedback' }));
 await waitFor(() => expect(updated).toHaveBeenCalledOnce());
 expect(mocks.grade).toHaveBeenCalledWith('allocation', expect.objectContaining({ grade_received: 0, instructor_feedback: 'Reviewed by educator' }));
});
